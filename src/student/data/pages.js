const SETS = {
  caofangzi: { pages: CAOFANGZI, label: '示例内页 · 乡村成长题材' },
  daocaoren: { pages: DAOCAOREN, label: '示例内页 · 田野寓言题材' },
  andersen: { pages: ANDERSEN, label: '示例内页 · 童话题材' },
}
const GENERIC_SET = { pages: GENERIC, label: '示例内页 · 通用示例读本' }

// 取某本书的示例内页集合。
// 返回 { pages, label, first, last, count, chapters }
export function getBookPages(bookId) {
  const set = SETS[bookId] || GENERIC_SET
  const pages = set.pages
  const chapters = []
  pages.forEach((p, i) => {
    const last = chapters[chapters.length - 1]
    if (!last || last.title !== p.chapter) chapters.push({ title: p.chapter, from: p.no, index: i })
    else last.to = p.no
  })
  chapters.forEach((c, i) => {
    c.to = i + 1 < chapters.length ? chapters[i + 1].from - 1 : pages[pages.length - 1].no
  })
  return {
    pages,
    label: set.label,
    demo: !SETS[bookId],
    first: pages[0].no,
    last: pages[pages.length - 1].no,
    count: pages.length,
    chapters,
  }
}

// 页码 → 示例内页数组下标；不在范围内返回 -1
export function indexOfPage(bookId, pageNo) {
  const { pages } = getBookPages(bookId)
  return pages.findIndex((p) => p.no === Number(pageNo))
}

// 某页的纯文本（Stage 4 把它喂给竹娃时用同一个口径）
export function pageText(page) {
  if (!page) return ''
  return page.blocks.map((b) => b.t).join('\n')
}

